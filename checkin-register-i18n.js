// checkin-register-i18n.js: the registration page in Polish, German and
// Arabic (English is the source text and the fallback). Keys are the
// English text exactly as the page uses it; {name}-style placeholders are
// filled by tr(). tests/checkin-register-i18n.spec.ts fails when the page
// gains a string that is missing here, in any language.
//
// Only CueDeck's own wording is translated. What the organizer typed (event
// name, description, questions, ticket names) is shown as they wrote it.

export const PAGE_LANGS = ['en', 'pl', 'de', 'ar'];
export const RTL = new Set(['ar']);

// The organizer's choice ('auto' or a language), else the guest's browser.
export function pickLang(setting, navLangs) {
  if (setting && setting !== 'auto' && PAGE_LANGS.includes(setting)) return setting;
  for (const l of navLangs || []) {
    const base = String(l).toLowerCase().split('-')[0];
    if (PAGE_LANGS.includes(base)) return base;
  }
  return 'en';
}

export function translate(lang, text, vars) {
  const s = (lang !== 'en' && DICT[lang] && DICT[lang][text]) || text;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

