// lines: [{ text, scale }] (scale = dots per font pixel). Centred across `across` dots.
export function textImage(lines, across = 696) {
  const gap = (s) => Math.round(s * 3);
  const rows = lines.map(l => ({ text: String(l.text).toUpperCase(), s: l.scale }));
  const h = rows.reduce((t, r) => t + r.s * 7 + gap(r.s), gap(rows[0].s));
  const gray = new Uint8Array(across * h).fill(255);
  let y = gap(rows[0].s);
  for (const { text, s } of rows) {
    const width = text.length * 6 * s - s;
    let x = Math.max(0, Math.floor((across - width) / 2));
    for (const ch of text) {
      const g = G[ch] || G[' '];
      for (let py = 0; py < 7; py++) for (let px = 0; px < 5; px++) {
        if (g[py * 5 + px] !== '1') continue;
        for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) {
          const X = x + px * s + dx, Y = y + py * s + dy;
          if (X < across) gray[Y * across + X] = 0;
        }
      }
      x += 6 * s;
    }
    y += s * 7 + gap(s);
  }
  return { w: across, h, gray };
}
